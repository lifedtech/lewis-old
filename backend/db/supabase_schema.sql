-- ==============================================================================
-- Isolated Supabase Database Schema for LEWIS Engine
-- Keeps LEWIS user data completely separate from Onboarding tables while
-- providing an anonymized activity analytics view for the Onboarding system.
-- Copy and paste into your Supabase SQL Editor (https://app.supabase.com)
-- ==============================================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Dedicated LEWIS Users Table (Isolated from Onboarding users)
CREATE TABLE IF NOT EXISTS public.lewis_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    name TEXT,
    password_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    source_portal TEXT DEFAULT 'lewis_app',
    role TEXT DEFAULT 'user',
    status TEXT DEFAULT 'active',
    last_login_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Dedicated LEWIS Sessions Table
CREATE TABLE IF NOT EXISTS public.lewis_sessions (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.lewis_users(id) ON DELETE CASCADE,
    ip_address TEXT,
    user_agent TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Dedicated LEWIS Report Vault
CREATE TABLE IF NOT EXISTS public.lewis_user_report_vault (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.lewis_users(id) ON DELETE CASCADE,
    report_uuid TEXT UNIQUE NOT NULL,
    report_title TEXT,
    wellbeing_band TEXT,
    overall_score DOUBLE PRECISION,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Dedicated LEWIS Anonymized Insight Reports Corpus
CREATE TABLE IF NOT EXISTS public.lewis_anonymized_insight_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_uuid TEXT UNIQUE NOT NULL,
    anonymous_code TEXT NOT NULL,
    wellbeing_band TEXT,
    overall_score DOUBLE PRECISION,
    deidentified_scores_json JSONB NOT NULL,
    deidentified_answers_json JSONB NOT NULL,
    deidentified_report_json JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- ONBOARDING SYSTEM ANALYTICS VIEW
-- Allows the Onboarding system to query overall usage stats WITHOUT mixing data.
-- Onboarding system can run: SELECT * FROM public.lewis_onboarding_analytics_summary;
-- ==============================================================================
CREATE OR REPLACE VIEW public.lewis_onboarding_analytics_summary AS
SELECT 
    (SELECT COUNT(DISTINCT id) FROM public.lewis_users) AS total_registered_lewis_users,
    (SELECT COUNT(DISTINCT anonymous_code) FROM public.lewis_anonymized_insight_reports) AS total_active_subjects,
    (SELECT COUNT(id) FROM public.lewis_anonymized_insight_reports) AS total_assessments_completed,
    (SELECT MAX(created_at) FROM public.lewis_anonymized_insight_reports) AS last_assessment_time;

-- Indexes for high performance
CREATE INDEX IF NOT EXISTS idx_lewis_users_email ON public.lewis_users(email);
CREATE INDEX IF NOT EXISTS idx_lewis_sessions_user_id ON public.lewis_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_lewis_vault_user_id ON public.lewis_user_report_vault(user_id);
CREATE INDEX IF NOT EXISTS idx_lewis_anon_reports_uuid ON public.lewis_anonymized_insight_reports(report_uuid);

-- ==============================================================================
-- SECURITY: default-deny for anon/authenticated, service_role only.
--
-- The FastAPI backend is the ONLY intended caller of these tables, and it
-- authenticates to Supabase with a service-role-class key. Supabase's
-- `service_role` Postgres role carries BYPASSRLS and is already granted
-- broad privileges on `public` by the project itself — it does not need,
-- and must never be given, a permissive RLS policy. A policy written
-- "for service role" that isn't actually restricted `TO service_role` has
-- no effect on service_role (which ignores RLS regardless) and instead
-- becomes the effective grant for every OTHER role that can reach the
-- table (anon, authenticated) — that was the bug: `USING (true)` with no
-- `TO` clause applies to PUBLIC, not to service_role.
--
-- The fix below is intentionally NOT "write a scoped per-user policy"
-- for anon/authenticated: this app does not use Supabase Auth (auth.py is
-- a self-contained custom auth system; lewis_users is not auth.users, so
-- `auth.uid()` has no meaningful relationship to a lewis_users row). There
-- is no correct per-row predicate to write for those roles today. Direct
-- browser/anon access to these tables is not a supported access path, so
-- the correct policy is no policy at all (RLS enabled + zero matching
-- policies = default deny for every role except one with BYPASSRLS),
-- backed up by an explicit REVOKE of the base table grants Supabase may
-- have created by default when these tables were first created.
--
-- Idempotent: safe to re-run against an existing project as a migration.
-- ==============================================================================

ALTER TABLE public.lewis_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lewis_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lewis_user_report_vault ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lewis_anonymized_insight_reports ENABLE ROW LEVEL SECURITY;

-- Drop the old, effectively-PUBLIC policies (SEC-001).
DROP POLICY IF EXISTS "Allow service role full access on lewis_users" ON public.lewis_users;
DROP POLICY IF EXISTS "Allow service role full access on lewis_vault" ON public.lewis_user_report_vault;
DROP POLICY IF EXISTS "Allow service role full access on lewis_anon_reports" ON public.lewis_anonymized_insight_reports;
-- No policy is created to replace them — see comment block above.

-- Belt-and-suspenders: even if RLS were ever accidentally disabled on one
-- of these tables in a future migration, anon/authenticated still could
-- not read/write a row without a base table grant. Revoke it explicitly
-- rather than relying on RLS alone (per SEC-001/SEC-002 remediation).
REVOKE ALL ON public.lewis_users FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.lewis_sessions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.lewis_user_report_vault FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.lewis_anonymized_insight_reports FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.lewis_onboarding_analytics_summary FROM PUBLIC, anon, authenticated;

-- Explicit (defensive, usually already implied by the project's own
-- default service_role grants) — make sure the backend is never blocked.
GRANT ALL PRIVILEGES ON public.lewis_users TO service_role;
GRANT ALL PRIVILEGES ON public.lewis_sessions TO service_role;
GRANT ALL PRIVILEGES ON public.lewis_user_report_vault TO service_role;
GRANT ALL PRIVILEGES ON public.lewis_anonymized_insight_reports TO service_role;
GRANT SELECT ON public.lewis_onboarding_analytics_summary TO service_role;

-- Sequences backing the BIGINT GENERATED BY DEFAULT AS IDENTITY columns
-- also need explicit grants for service_role INSERTs to work under RLS+
-- REVOKE tightening — without this, inserts can fail with a permission
-- error on the identity sequence even though the table grant is correct.
DO $$
DECLARE seq RECORD;
BEGIN
  FOR seq IN
    SELECT sequence_name FROM information_schema.sequences
    WHERE sequence_schema = 'public' AND sequence_name LIKE 'lewis_%'
  LOOP
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO service_role', seq.sequence_name);
    EXECUTE format('REVOKE ALL ON SEQUENCE public.%I FROM PUBLIC, anon, authenticated', seq.sequence_name);
  END LOOP;
END $$;
