-- ==============================================================================
-- Isolated Supabase Database Schema for LEWIS Engine
-- Keeps LEWIS user data completely separate from Onboarding tables while
-- providing an anonymized activity analytics view for the Onboarding system.
-- Copy and paste into your Supabase SQL Editor (https://app.supabase.com)
-- ==============================================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Dedicated LEWIS Users Table (Isolated from Onboarding users)
CREATE TABLE IF NOT EXISTS public.lewis_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    name TEXT,
    password_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    source_portal TEXT DEFAULT 'lewis_app',
    role TEXT DEFAULT 'user',
    status TEXT DEFAULT 'active',
    last_login_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Dedicated LEWIS Sessions Table
CREATE TABLE IF NOT EXISTS public.lewis_sessions (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.lewis_users(id) ON DELETE CASCADE,
    ip_address TEXT,
    user_agent TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Dedicated LEWIS Report Vault
CREATE TABLE IF NOT EXISTS public.lewis_user_report_vault (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.lewis_users(id) ON DELETE CASCADE,
    report_uuid TEXT UNIQUE NOT NULL,
    report_title TEXT,
    wellbeing_band TEXT,
    overall_score DOUBLE PRECISION,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Dedicated LEWIS Anonymized Insight Reports Corpus
CREATE TABLE IF NOT EXISTS public.lewis_anonymized_insight_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_uuid TEXT UNIQUE NOT NULL,
    anonymous_code TEXT NOT NULL,
    wellbeing_band TEXT,
    overall_score DOUBLE PRECISION,
    deidentified_scores_json JSONB NOT NULL,
    deidentified_answers_json JSONB NOT NULL,
    deidentified_report_json JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- ONBOARDING SYSTEM ANALYTICS VIEW
-- Allows the Onboarding system to query overall usage stats WITHOUT mixing data.
-- Onboarding system can run: SELECT * FROM public.lewis_onboarding_analytics_summary;
-- ==============================================================================
CREATE OR REPLACE VIEW public.lewis_onboarding_analytics_summary AS
SELECT 
    (SELECT COUNT(DISTINCT id) FROM public.lewis_users) AS total_registered_lewis_users,
    (SELECT COUNT(DISTINCT anonymous_code) FROM public.lewis_anonymized_insight_reports) AS total_active_subjects,
    (SELECT COUNT(id) FROM public.lewis_anonymized_insight_reports) AS total_assessments_completed,
    (SELECT MAX(created_at) FROM public.lewis_anonymized_insight_reports) AS last_assessment_time;

-- Indexes for high performance
CREATE INDEX IF NOT EXISTS idx_lewis_users_email ON public.lewis_users(email);
CREATE INDEX IF NOT EXISTS idx_lewis_sessions_user_id ON public.lewis_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_lewis_vault_user_id ON public.lewis_user_report_vault(user_id);
CREATE INDEX IF NOT EXISTS idx_lewis_anon_reports_uuid ON public.lewis_anonymized_insight_reports(report_uuid);

-- Security Policies
ALTER TABLE public.lewis_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lewis_user_report_vault ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lewis_anonymized_insight_reports ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow service role full access on lewis_users" ON public.lewis_users FOR ALL USING (true);
CREATE POLICY "Allow service role full access on lewis_vault" ON public.lewis_user_report_vault FOR ALL USING (true);
CREATE POLICY "Allow service role full access on lewis_anon_reports" ON public.lewis_anonymized_insight_reports FOR ALL USING (true);
