-- ==============================================================================
-- Supabase Database Schema for LEWIS Engine & LifedHealth User Portal
-- Copy and paste this script into your Supabase SQL Editor (https://app.supabase.com)
-- ==============================================================================

-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Users Table (Shared with LifedHealth User Portal)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    name TEXT,
    password_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    source_portal TEXT DEFAULT 'lifedhealth',
    role TEXT DEFAULT 'user',
    status TEXT DEFAULT 'active',
    last_login_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Sessions Table
CREATE TABLE IF NOT EXISTS public.sessions (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    ip_address TEXT,
    user_agent TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. User Report Vault (Links authenticated user profile to report_uuid for Portal view)
CREATE TABLE IF NOT EXISTS public.user_report_vault (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    report_uuid TEXT UNIQUE NOT NULL,
    report_title TEXT,
    wellbeing_band TEXT,
    overall_score DOUBLE PRECISION,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Anonymized Insight Reports Corpus (Zero PII, masked code for ML/System Enhancement)
CREATE TABLE IF NOT EXISTS public.anonymized_insight_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_uuid TEXT UNIQUE NOT NULL,
    anonymous_code TEXT NOT NULL,
    wellbeing_band TEXT,
    overall_score DOUBLE PRECISION,
    deidentified_scores_json JSONB NOT NULL,
    deidentified_answers_json JSONB NOT NULL,
    deidentified_report_json JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for lightning fast queries
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);
CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON public.sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_vault_user_id ON public.user_report_vault(user_id);
CREATE INDEX IF NOT EXISTS idx_anon_reports_uuid ON public.anonymized_insight_reports(report_uuid);
CREATE INDEX IF NOT EXISTS idx_anon_code ON public.anonymized_insight_reports(anonymous_code);

-- Enable Row Level Security (RLS) on public.users & vault
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_report_vault ENABLE ROW LEVEL SECURITY;

-- Allow service_role key full access
CREATE POLICY "Allow service role full access on users" ON public.users FOR ALL USING (true);
CREATE POLICY "Allow service role full access on vault" ON public.user_report_vault FOR ALL USING (true);
CREATE POLICY "Allow service role full access on anonymized reports" ON public.anonymized_insight_reports FOR ALL USING (true);
